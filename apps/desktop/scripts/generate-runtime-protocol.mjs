import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const desktopRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repositoryRoot = path.resolve(desktopRoot, "../..");
const sourcePath = path.join(repositoryRoot, "packages/runtime-protocol/src/index.ts");
const legacyPath = path.join(desktopRoot, "electron/generated/runtime-protocol.ts");

// The shared TypeScript package is the protocol source of truth. Reading it here
// fails early if the package is missing.
readFileSync(sourcePath, "utf8");

const legacy =
  '// Generated by pnpm protocol:generate from @agentkib/runtime-protocol.\nexport * from "@agentkib/runtime-protocol";\n';
let current = "";
try {
  current = readFileSync(legacyPath, "utf8");
} catch {
  // The compatibility entry point does not exist yet.
}

if (current !== legacy) writeFileSync(legacyPath, legacy);
