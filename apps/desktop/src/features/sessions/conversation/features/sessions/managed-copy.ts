export function managedText(
  locale: Locale,
  english: string,
  chinese: string,
  surface: SessionSurface = "desktop",
) {
  const text =
    locale === "en-US"
      ? english
      : locale === "zh-CN"
        ? chinese
        : (copy[chinese]?.[locale === "zh-TW" ? 0 : 1] ?? chinese);
  return surfaceText(text, surface, locale);
}
