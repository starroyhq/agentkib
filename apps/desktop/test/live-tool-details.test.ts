// Live projections must produce the same detail shape as history. Codex frames
// follow the app-server definitions generated by CLI 0.163.0; Claude frames
// are played by the scripted fake CLI. Both are synthetic.
const cleanups: Array<() => void | Promise<void>> = [];
afterEach(async () => {
  vi.restoreAllMocks();
  for (const cleanup of cleanups.splice(0).reverse()) await cleanup();
});

const threadId = "01234567-89ab-cdef-0123-456789abcdef";
const workspace = "/home/tester/work/project";
function codex() {
  const state = new ManagedCodexState({
    id: "managed",
    workspace_id: "workspace",
    workspace,
    native_id: threadId,
  });
  state.apply({
    method: "turn/started",
    params: { threadId, turn: { id: "turn-a", status: "inProgress" } },
  });
  return state;
}
const commandItem = {
  type: "commandExecution",
  id: "item-cmd",
  command: "/bin/zsh -lc 'pnpm test'",
  cwd: workspace,
  processId: null,
  source: "agent",
  status: "failed",
  commandActions: [{ type: "unknown", command: "pnpm test" }],
  aggregatedOutput: "1 failed\n",
  exitCode: 1,
  durationMs: 1200,
};
const fileItem = {
  type: "fileChange",
  id: "item-patch",
  changes: [
    {
      path: `${workspace}/src/app.ts`,
      kind: { type: "update", move_path: null },
      diff: "@@ -1 +1 @@\n-a\n+b\n",
    },
  ],
  status: "completed",
};

describe("live Codex projection", () => {
  it("projects completed app-server items with the shared detail shape", () => {
    const state = codex();
    const command = state.apply({
      method: "item/completed",
      params: { threadId, turnId: "turn-a", item: commandItem, completedAtMs: 1 },
    }).event!;
    expect(command).toMatchObject({
      id: "item-cmd",
      kind: "tool-summary",
      turn_id: "turn-a",
      tool_name: "shell",
      tool_status: "failed",
      duration_ms: 1200,
      tool: {
        kind: "execute",
        title: "pnpm test",
        content: [{ type: "terminal", command: "pnpm test", output: "1 failed\n", exit_code: 1 }],
      },
    });
    const patch = state.apply({
      method: "item/completed",
      params: { threadId, turnId: "turn-a", item: fileItem, completedAtMs: 2 },
    }).event!;
    expect(patch).toMatchObject({
      tool_name: "apply_patch",
      tool: {
        kind: "edit",
        title: "src/app.ts",
        content: [{ type: "diff", path: "src/app.ts", added: 1, removed: 1 }],
      },
    });
    const agent = state.apply({
      method: "item/completed",
      params: {
        threadId,
        turnId: "turn-a",
        item: {
          type: "subAgentActivity",
          id: "item-agent",
          kind: "started",
          agentThreadId: "t",
          agentPath: "/root/reviewer",
          model: null,
          reasoningEffort: null,
        },
        completedAtMs: 3,
      },
    }).event!;
    expect(agent).toMatchObject({
      tool: { kind: "other", agent: { action: "spawn", name: "reviewer" } },
    });
    expect(
      state.apply({
        method: "item/completed",
        params: {
          threadId,
          turnId: "turn-a",
          item: { type: "reasoning", id: "r", summary: ["x"], content: [] },
          completedAtMs: 4,
        },
      }).event,
    ).toBeUndefined();
  });

  // Found with a real gpt-6-luna turn: turn/completed carries durationMs (38584 there),
  // but connected managed sessions read history from these live rows.
  it("adds the reported turn duration to the turn's last live row", () => {
    const state = codex();
    state.apply({
      method: "item/completed",
      params: { threadId, turnId: "turn-a", item: commandItem, completedAtMs: 1 },
    });
    const reply = state.apply({
      method: "item/completed",
      params: {
        threadId,
        turnId: "turn-a",
        item: { type: "agentMessage", id: "msg-final", text: "Fixed.", phase: "final_answer" },
        completedAtMs: 2,
      },
    }).event!;
    expect(reply.turn_meta).toBeUndefined();
    // The phase groups commentary inside the turn's process, as rollout history does.
    expect(reply.message_phase).toBe("final_answer");
    const completed = state.apply({
      method: "turn/completed",
      params: {
        threadId,
        turn: { id: "turn-a", status: "completed", error: null, durationMs: 38_584, items: [] },
      },
    });
    expect(completed.changed).toBe(true);
    expect(completed.event).toMatchObject({
      id: "msg-final",
      kind: "agent-message",
      content: "Fixed.",
      turn_meta: { outcome: "completed", duration_ms: 38_584 },
    });
    expect(state.status).toBe("idle");

    const interrupted = codex();
    interrupted.apply({
      method: "item/completed",
      params: { threadId, turnId: "turn-a", item: commandItem, completedAtMs: 1 },
    });
    expect(
      interrupted.apply({
        method: "turn/completed",
        params: { threadId, turn: { id: "turn-a", status: "interrupted", durationMs: 900 } },
      }).event,
    ).toMatchObject({ id: "item-cmd", turn_meta: { outcome: "aborted", duration_ms: 900 } });

    const empty = codex();
    expect(
      empty.apply({
        method: "turn/completed",
        params: { threadId, turn: { id: "turn-a", status: "completed", durationMs: 5 } },
      }).event,
    ).toBeUndefined();
  });

  it("hydrates thread/read turns the same way", () => {
    const state = new ManagedCodexState({
      id: "managed",
      workspace_id: "workspace",
      workspace,
      native_id: threadId,
    });
    const { events } = state.hydrate({
      id: threadId,
      turns: [{ id: "turn-h", status: "completed", items: [commandItem, fileItem] }],
    });
    expect(events.map((event) => [event.tool_name, (event.tool as { kind: string }).kind])).toEqual(
      [
        ["shell", "execute"],
        ["apply_patch", "edit"],
      ],
    );
    // Like the rollout reader: a finished turn without a duration still records its outcome.
    expect(events.map((event) => event.turn_meta)).toEqual([undefined, { outcome: "completed" }]);
  });

  it("hydrates each finished turn's duration onto its last row", () => {
    const state = new ManagedCodexState({
      id: "managed",
      workspace_id: "workspace",
      workspace,
      native_id: threadId,
    });
    const { events } = state.hydrate({
      id: threadId,
      turns: [
        {
          id: "turn-1",
          status: "completed",
          error: null,
          durationMs: 1200,
          items: [commandItem, fileItem],
        },
        {
          id: "turn-2",
          status: "inProgress",
          durationMs: null,
          items: [{ ...commandItem, id: "c2" }],
        },
      ],
    });
    expect(events.map((event) => [event.id, event.turn_meta ?? null])).toEqual([
      ["item-cmd", null],
      ["item-patch", { outcome: "completed", duration_ms: 1200 }],
      ["c2", null],
    ]);
    // The running turn it attached to can still finish with a duration.
    expect(
      state.apply({
        method: "turn/completed",
        params: { threadId, turn: { id: "turn-2", status: "completed", durationMs: 40 } },
      }).event,
    ).toMatchObject({ id: "c2", turn_meta: { outcome: "completed", duration_ms: 40 } });
  });
});

describe("managed ledger turn duration", () => {
  it("adds turn_meta to an item that is already stored without rewriting it", () => {
    const root = mkdtempSync(join(tmpdir(), "agentkib-ledger-turn-"));
    cleanups.push(() => rmSync(root, { recursive: true, force: true }));
    const record = {
      id: "managed",
      workspace_id: "workspace",
      workspace,
      home: "/home/tester/.codex",
      native_id: threadId,
      title: "Fixture",
      created_at: "2026-10-27T00:00:00Z",
      released: false,
      archived: false,
      policy_id: "workspace-write-on-request",
      snapshot: { revision: 0, status: "idle" },
    };
    saveManagedRecord(root, record);
    const persist = createManagedSnapshotWriter(root, record);
    const state = codex();
    const first = { id: "msg-final", kind: "agent-message", turn_id: "turn-a", content: "Fixed." };
    persist(state, first);
    // A repeated write keeps the first-written row.
    persist(state, { ...first, content: "Changed." });
    persist(state, {
      ...first,
      content: "Changed.",
      turn_meta: { outcome: "completed", duration_ms: 7 },
    });
    expect(readManagedEvents(root, "managed", null, 50).events).toEqual([
      { ...first, turn_meta: { outcome: "completed", duration_ms: 7 } },
    ]);
  });
});

describe.skipIf(!["darwin", "linux"].includes(process.platform))("live Claude projection", () => {
  it("shows the command at tool_use and its output at tool_result", async () => {
    const f = createFakeClaude("agentkib-claude-tools-");
    cleanups.push(() => rmSync(f.root, { recursive: true, force: true }));
    f.setPlan({
      onUser: [
        {
          type: "assistant",
          parent_tool_use_id: null,
          message: {
            content: [
              {
                type: "tool_use",
                id: "toolu_live_bash",
                name: "Bash",
                input: { command: "npm test" },
              },
            ],
          },
        },
        {
          type: "user",
          message: {
            content: [{ type: "tool_result", tool_use_id: "toolu_live_bash", content: "3 passed" }],
          },
        },
        {
          type: "assistant",
          parent_tool_use_id: null,
          message: {
            content: [
              {
                type: "tool_use",
                id: "toolu_live_edit",
                name: "Edit",
                input: {
                  file_path: `${f.workspace}/src/a.ts`,
                  old_string: "one\ntwo",
                  new_string: "one\nTWO",
                },
              },
            ],
          },
        },
        {
          type: "user",
          message: {
            content: [{ type: "tool_result", tool_use_id: "toolu_live_edit", content: "updated" }],
          },
          tool_use_result: { filePath: `${f.workspace}/src/a.ts`, originalFile: "SECRET-ORIGINAL" },
        },
      ],
    });
    const events: Array<{ type: string; payload: Record<string, any> }> = [];
    const runner = new ClaudeManagedRunnerProcess(
      f.workspace,
      randomUUID(),
      true,
      0,
      f.environment,
      () => undefined,
      true,
      (type, payload) => events.push({ type, payload: structuredClone(payload) }),
      {},
    );
    cleanups.push(async () => {
      await runner.shutdown().catch(() => undefined);
    });
    await runner.send(f.executable, "synthetic turn", randomUUID(), runner.snapshot().revision);
    await expect.poll(() => runner.snapshot().status, { timeout: 15_000 }).toBe("idle");
    const items = events.flatMap(({ type, payload }) =>
      type === "item-upsert" ? [payload] : type === "snapshot" ? (payload.items ?? []) : [],
    );
    const bash = items.filter((item) => item.id === "toolu_live_bash");
    expect(bash[0]).toMatchObject({
      tool_status: "running",
      tool: {
        kind: "execute",
        title: "npm test",
        content: [{ type: "terminal", command: "npm test" }],
      },
    });
    expect(bash.at(-1)).toMatchObject({
      tool_status: "completed",
      tool: { content: [{ type: "terminal", command: "npm test", output: "3 passed" }] },
    });
    const edit = items.filter((item) => item.id === "toolu_live_edit").at(-1)!;
    expect(edit.tool).toMatchObject({
      kind: "edit",
      title: "src/a.ts",
      content: [{ type: "diff", path: "src/a.ts", added: 1, removed: 1 }],
    });
    expect(JSON.stringify(events)).not.toContain("SECRET-ORIGINAL");
  }, 30_000);
});
