/**
 * Sessions of Devin CLI and Devin Desktop, read from the SQLite store they share. AgentKib only
 * reads: the database is opened read-only inside one read transaction, hidden (internal) sessions
 * are skipped, and continuing a session stays in Devin.
 */
export class DevinSessions {
  /**
   * Walking a long session's chains is the slow part of a read, and paging repeats it. The walk
   * is kept briefly for an unchanged head; any new message or compaction moves the head.
   */
  #histories = new Map<string, { at: number; history: History }>();
  constructor(readonly environment: NodeJS.ProcessEnv) {}
  database(): string {
    return devinSessionDatabase(this.environment);
  }
  #read<T>(read: (source: Source) => T): T | null {
    const source = openSource(this.database());
    if (!source) return null;
    try {
      const value = read(source);
      source.verify();
      return value;
    } finally {
      source.db.close();
    }
  }
  #history<T>(
    ref: string,
    workspace: string,
    read: (source: Source, session: Session, history: History) => T,
  ): T {
    const value = this.#read((source) => {
      if (!source.history)
        throw new Error("This Devin version stores history in a format AgentKib cannot read yet");
      const session = ownedSession(source, ref, workspace);
      if (session.head === null) throw new Error("Devin session has no readable history");
      const key = JSON.stringify([this.database(), session.id, session.head, session.updated]);
      const cached = this.#histories.get(key);
      const history =
        cached && Date.now() - cached.at < 30_000 ? cached.history : readHistory(source, session);
      this.#histories.delete(key);
      this.#histories.set(key, {
        at: cached?.history === history ? cached.at : Date.now(),
        history,
      });
      while (this.#histories.size > 4) this.#histories.delete(this.#histories.keys().next().value!);
      return read(source, session, history);
    });
    if (value === null) throw new Error("Devin session history is no longer available");
    return value;
  }
  /** Sessions whose working directory is inside `workspace`; null lists every session. */
  list(workspace: string | null): { sessions: NativeSession[]; incomplete: boolean } {
    const listing = this.#read((source) => {
      const rows = source.db
        .prepare(
          `SELECT ${SESSION_COLUMNS(source)} FROM sessions WHERE hidden=0 ORDER BY last_activity_at DESC LIMIT ${MAX_SESSIONS + 1}`,
        )
        .all();
      let incomplete = rows.length > MAX_SESSIONS;
      const sessions: NativeSession[] = [];
      for (const row of rows.slice(0, MAX_SESSIONS)) {
        const session = sessionRow(row);
        if (!session) {
          incomplete = true;
          continue;
        }
        if (workspace !== null && !within(session.cwd, workspace)) continue;
        if (isProbeWorkspace(session.cwd)) continue;
        sessions.push({
          native_ref: session.id,
          agent: "devin",
          title: sessionTitle(session.title),
          created_at: session.created,
          updated_at: session.updated,
          message_count: null,
          git_branch: null,
          archived: false,
          sidechain: false,
          availability: source.history && session.head !== null ? "readable" : "metadata-only",
          origin: "interactive",
          spawned_by_session_id: null,
          forked_from_session_id: null,
          cwd: session.cwd,
        });
      }
      return { sessions, incomplete };
    });
    return listing ?? { sessions: [], incomplete: false };
  }
  /** One page, newest first; the cursor names the first item of the previous page. */
  events(
    ref: string,
    workspace: string,
    cursor: string | null,
    limit: number,
  ): ConversationEventPage {
    return this.#history(ref, workspace, (source, session, history) => {
      const items = project(
        history.segments.flatMap((segment) => segment.nodes),
        new Set(),
      );
      phases(items);
      let end = items.length;
      if (cursor !== null) {
        if (!cursor.startsWith(CURSOR)) throw new Error("Invalid Devin history cursor");
        end = items.findIndex((item) => item.id === cursor.slice(CURSOR.length));
        if (end < 0) throw new Error("Devin history changed while it was being read");
      }
      const slice = items.slice(Math.max(0, end - Math.min(100, Math.max(1, limit))), end);
      const tools = slice.filter((item) => item.type === "tool");
      const bodies = readBodies(source, session.id, [
        ...slice.filter((item) => item.type !== "tool").map((item) => item.node.node),
        ...tools.map((item) => item.node.node),
        ...tools.flatMap((item) => (item.result ? [item.result.node] : [])),
      ]);
      const states = readToolStates(
        source,
        session.id,
        tools.map((item) => item.call.id),
      );
      const context: ToolContext = { workspace, cwd: session.cwd };
      const events: ConversationEvent[] = [];
      let bytes = 0;
      let start = end;
      // Fill from the newest item back, within the page budget; a page keeps at least one item.
      for (let index = slice.length - 1; index >= 0; index--) {
        const item = slice[index]!;
        const event =
          item.type === "tool"
            ? toolEvent(
                item,
                states.get(item.call.id),
                bodies.get(item.node.node)?.arguments.get(item.call.id),
                item.result ? (bodies.get(item.result.node)?.content ?? null) : null,
                context,
              )
            : messageEvent(item, bodies.get(item.node.node));
        bytes += eventBytes(event);
        if (events.length && bytes > MAX_PAGE_BYTES) break;
        events.unshift(event);
        start = end - events.length;
      }
      return {
        events,
        next_cursor: start > 0 ? `${CURSOR}${items[start]!.id}` : null,
        warnings: history.partial ? [PARTIAL_HISTORY] : [],
      };
    });
  }
  /**
   * The session as a handoff document. By default it holds what Devin's model sees now: the
   * latest compaction summary and what followed, with the replaced history counted as
   * `compacted-history`. `includePreCompactionHistory` keeps every segment, with a marker where
   * Devin compacted.
   */
  document(
    ref: string,
    workspace: string,
    source: DocumentSource,
    options: DocumentOptions = {},
  ): SessionDocument {
    const withHistory = options.includePreCompactionHistory === true;
    const { turns, losses } = this.#history(ref, workspace, (db, session, history) => {
      const losses = new Map<LossCode, number>();
      const loss = (code: LossCode, count = 1) => {
        if (count > 0) losses.set(code, (losses.get(code) ?? 0) + count);
      };
      const turns: Turn[] = [];
      const newest = history.segments.length - 1;
      const total = history.segments.filter((segment) => segment.summary).length;
      const seen = new Set<string>();
      const images = { remaining: MAX_DOCUMENT_IMAGE_CHARS };
      let ordinal = 0;
      for (const [index, segment] of history.segments.entries()) {
        if (!withHistory && index < newest) {
          loss("compacted-history", project(segment.nodes, new Set()).length);
          continue;
        }
        if (segment.summary) {
          ordinal++;
          if (withHistory)
            turns.push({
              id: `devin-boundary-${segment.summary.node}`,
              role: "user",
              kind: "compaction-boundary",
              timestamp: segment.summary.time,
              blocks: [
                {
                  type: "text",
                  text: `[AgentKib: Devin compacted the conversation here (compaction ${ordinal} of ${total}). Messages above are the original earlier history; the context summary below is what Devin carried forward.]`,
                },
              ],
            });
          const summary = readBodies(db, session.id, [segment.summary.node]).get(
            segment.summary.node,
          );
          if (summary?.truncated) loss("source-content-truncated");
          if (summary?.content?.trim())
            turns.push({
              id: `devin-summary-${segment.summary.node}`,
              role: "user",
              kind: "context-summary",
              timestamp: segment.summary.time,
              blocks: [{ type: "text", text: `${SUMMARY_NOTICE}\n\n${summary.content}` }],
            });
        }
        const items = project(segment.nodes, withHistory ? seen : new Set());
        turns.push(...documentTurns(db, session, items, images, loss));
      }
      if (history.partial) loss("compaction-link-unavailable");
      return { turns, losses };
    });
    return finishDocument(source, turns, losses);
  }
  /**
   * What content search finds: every message, tool input and tool output, including history a
   * compaction replaced. Compaction summaries are Devin's, not the conversation's, and are left out.
   */
  searchRecords(
    ref: string,
    workspace: string,
  ): { fingerprint: string; records: DevinSearchRecord[] } {
    return this.#history(ref, workspace, (source, session, history) => {
      const items = project(
        history.segments.flatMap((segment) => segment.nodes),
        new Set(),
      );
      const records: DevinSearchRecord[] = [];
      const digest = createHash("sha256").update(
        JSON.stringify([session.id, session.head, session.updated, history.partial]),
      );
      // Bodies are read a bounded batch at a time so a long session never sits in memory whole.
      for (let start = 0; start < items.length; start += 200) {
        const batch = items.slice(start, start + 200);
        const bodies = readBodies(source, session.id, [
          ...batch.map((item) => item.node.node),
          ...batch.flatMap((item) =>
            item.type === "tool" && item.result ? [item.result.node] : [],
          ),
        ]);
        for (const item of batch) {
          const body = bodies.get(item.node.node);
          const add = (
            recordId: string,
            kind: DevinSearchRecord["kind"],
            toolName: string | null,
            value: string | null | undefined,
            truncated: boolean,
          ) => {
            if (!value?.trim()) return;
            const content =
              value.length > MAX_SEARCH_CHARS ? value.slice(0, MAX_SEARCH_CHARS) : value;
            digest.update(`${recordId}\0${content}\0`);
            records.push({
              recordId,
              kind,
              toolName,
              timestamp: item.node.time,
              content,
              truncated: truncated || value.length > MAX_SEARCH_CHARS,
            });
          };
          if (item.type === "user")
            add(`${item.id}:text`, "user", null, body?.content, !!body?.truncated);
          else if (item.type === "reply")
            add(`${item.id}:text`, "assistant", null, body?.content, !!body?.truncated);
          else {
            add(
              `call:${item.call.id}:input`,
              "tool-input",
              item.call.name,
              body?.arguments.get(item.call.id),
              false,
            );
            if (item.result) {
              const result = bodies.get(item.result.node);
              add(
                `call:${item.call.id}:output`,
                "tool-output",
                item.call.name,
                result?.content,
                !!result?.truncated,
              );
            }
          }
        }
      }
      return { fingerprint: digest.digest("hex"), records };
    });
  }
  /** An image the user attached to a message of this session. */
  image(ref: string, workspace: string, imageId: string): { mimeType: string; base64: string } {
    const match = IMAGE_ID.exec(imageId);
    if (!match) throw new Error("session-image-unavailable");
    const node = Number(match[1]),
      index = Number(match[2]);
    const value = this.#read((source) => {
      if (!source.history) throw new Error("session-image-unavailable");
      const session = ownedSession(source, ref, workspace);
      // Paths are built from the validated integer index; a bound number arrives as a real.
      const row = source.db
        .prepare(
          `SELECT json_extract(chat_message,?3) AS mime,
             CASE WHEN length(json_extract(chat_message,?4))<=?5
               THEN json_extract(chat_message,?4) END AS data
           FROM message_nodes WHERE session_id=?1 AND node_id=?2 AND json_valid(chat_message)
             AND json_extract(chat_message,'$.role')='user'
             AND json_extract(chat_message,'$.metadata.is_user_input')=1`,
        )
        .get(
          session.id,
          node,
          `$.images[${index}].mime_type`,
          `$.images[${index}].base64_data`,
          MAX_IMAGE_CHARS,
        );
      const mime = typeof row?.mime === "string" ? row.mime.toLowerCase() : null;
      if (!mime || !IMAGE_TYPES.has(mime) || typeof row?.data !== "string")
        throw new Error("session-image-unavailable");
      return sessionImageResult(decodedSessionImage(row.data), mime);
    });
    if (!value) throw new Error("session-image-unavailable");
    return value;
  }
}

function documentTurns(
  source: Source,
  session: Session,
  items: Item[],
  images: { remaining: number },
  loss: (code: LossCode, count?: number) => void,
): Turn[] {
  const turns: Turn[] = [];
  // Kept across batches: a reply's calls can fall into the next batch.
  let reply: Turn | null = null;
  for (let start = 0; start < items.length; start += 200) {
    const batch = items.slice(start, start + 200);
    const tools = batch.filter((item) => item.type === "tool");
    const bodies = readBodies(source, session.id, [
      ...batch.map((item) => item.node.node),
      ...tools.flatMap((item) => (item.result ? [item.result.node] : [])),
    ]);
    const states = readToolStates(
      source,
      session.id,
      tools.map((item) => item.call.id),
    );
    for (const item of batch) {
      const body = bodies.get(item.node.node);
      if (body?.truncated) loss("source-content-truncated");
      if (item.type === "user") {
        reply = null;
        const blocks: Block[] = [];
        if (body?.content?.trim()) blocks.push({ type: "text", text: body.content });
        for (const [index, image] of (body?.images ?? []).entries()) {
          const supported = image.mime !== null && IMAGE_TYPES.has(image.mime);
          if (!supported || image.size > MAX_IMAGE_CHARS || image.size > images.remaining) {
            loss(supported ? "source-content-truncated" : "unsupported-attachment");
            continue;
          }
          const data = source.db
            .prepare(
              "SELECT json_extract(chat_message,?3) AS data FROM message_nodes WHERE session_id=?1 AND node_id=?2",
            )
            .get(session.id, item.node.node, `$.images[${index}].base64_data`)?.data;
          if (typeof data !== "string") {
            loss("damaged-record");
            continue;
          }
          images.remaining -= data.length;
          blocks.push({
            type: "attachment",
            kind: "image",
            media_type: image.mime!,
            inline_base64: data,
          });
        }
        if (blocks.length)
          turns.push({ id: item.id, role: "user", timestamp: item.node.time, blocks });
        continue;
      }
      // A reply and the calls Devin made with it are one assistant turn.
      if (!reply || reply.id !== `devin-turn-${item.node.node}`) {
        if (item.node.thinking) loss("reasoning-excluded");
        reply = {
          id: `devin-turn-${item.node.node}`,
          role: "assistant",
          timestamp: item.node.time,
          blocks: [],
        };
        turns.push(reply);
      }
      if (item.type === "reply") {
        if (body?.content?.trim()) reply.blocks.push({ type: "text", text: body.content });
        continue;
      }
      const input = body?.arguments.get(item.call.id) ?? "";
      if (input.length >= MAX_TEXT_CHARS) loss("source-content-truncated");
      reply.blocks.push({
        type: "tool-call",
        call_id: item.call.id,
        name: item.call.name,
        input,
      });
      if (!item.result) continue;
      const result = bodies.get(item.result.node);
      if (result?.truncated) loss("source-content-truncated");
      if (result?.images.length) loss("external-attachment", result.images.length);
      const status = states.get(item.call.id)?.update;
      turns.push({
        id: `devin-result-${item.result.node}`,
        role: "tool",
        timestamp: item.result.time,
        blocks: [
          {
            type: "tool-result",
            call_id: item.call.id,
            output: result?.content ?? "",
            is_error:
              status !== null && typeof status === "object" && "status" in status
                ? status.status === "failed"
                : false,
          },
        ],
      });
    }
  }
  // Empty assistant turns (a reply whose body is gone) are dropped rather than invented.
  return turns.filter((turn) => turn.blocks.length);
}
