interface Source {
  db: DatabaseSync;
  /** Messages are readable: the columns exist and Devin's compatibility marker is a known one. */
  history: boolean;
  tools: boolean;
  verify(): void;
}
function absent(error: unknown): boolean {
  return ["ENOENT", "ENOTDIR"].includes((error as NodeJS.ErrnoException).code ?? "");
}
/** Whether a regular file exists; a link or any other kind of entry is refused. */
function regular(file: string): boolean {
  try {
    const info = lstatSync(file);
    if (info.isSymbolicLink() || !info.isFile()) throw new Error("Unsafe Devin session database");
    return true;
  } catch (error) {
    if (absent(error)) return false;
    throw error;
  }
}
function columns(db: DatabaseSync, table: string): Set<string> {
  return new Set(
    db
      .prepare("SELECT name FROM pragma_table_info(?)")
      .all(table)
      .map((row) => String(row.name)),
  );
}
function openSource(file: string): Source | null {
  if (!regular(file)) return null;
  const sidecars = () => ["-wal", "-shm", "-journal"].filter((suffix) => regular(file + suffix));
  // A database no process has open is opened immutable, so reading it creates no sidecars. A live
  // one keeps normal locking: one read transaction sees one committed snapshot of Devin's writes.
  const closed = sidecars().length ? null : lstatSync(file, { bigint: true });
  const db = new DatabaseSync(closed ? `${pathToFileURL(file).href}?immutable=1` : file, {
    readOnly: true,
    timeout: 1000,
  });
  try {
    db.exec("PRAGMA query_only=ON; BEGIN DEFERRED");
    const sessions = columns(db, "sessions");
    if (
      !["id", "working_directory", "title", "created_at", "last_activity_at", "hidden"].every(
        (name) => sessions.has(name),
      )
    )
      throw new Error("Unsupported Devin session database");
    const nodes = columns(db, "message_nodes");
    const tools = columns(db, "tool_call_state");
    const compat = columns(db, "app_state").has("value")
      ? db.prepare("SELECT value FROM app_state WHERE key='schema_compat_version'").get()?.value
      : undefined;
    return {
      db,
      history:
        sessions.has("main_chain_id") &&
        ["session_id", "node_id", "parent_node_id", "chat_message", "metadata"].every((name) =>
          nodes.has(name),
        ) &&
        (compat === undefined || compat === null || COMPATIBLE_SCHEMAS.has(String(compat))),
      tools: ["session_id", "tool_call_id", "tool_call_json", "tool_call_update_json"].every(
        (name) => tools.has(name),
      ),
      verify() {
        if (!closed) return;
        const current = lstatSync(file, { bigint: true });
        if (
          current.dev !== closed.dev ||
          current.ino !== closed.ino ||
          current.size !== closed.size ||
          current.mtimeNs !== closed.mtimeNs ||
          current.ctimeNs !== closed.ctimeNs ||
          sidecars().length
        )
          throw new Error("Devin session database changed during read");
      },
    };
  } catch (error) {
    db.close();
    throw error;
  }
}

interface Session {
  id: string;
  cwd: string;
  title: string | null;
  created: string | null;
  updated: string | null;
  head: number | null;
}
const SESSION_COLUMNS = (source: Source) =>
  `id,substr(working_directory,1,4097) AS cwd,substr(title,1,1024) AS title,created_at,last_activity_at,${source.history ? "main_chain_id" : "NULL"} AS head`;
function sessionRow(row: Row): Session | null {
  const id = typeof row.id === "string" && SESSION_ID.test(row.id) ? row.id : null;
  const cwd =
    typeof row.cwd === "string" && row.cwd.length <= 4096 && path.isAbsolute(row.cwd)
      ? row.cwd
      : null;
  if (!id || !cwd) return null;
  const created = jsonTimestamp(row.created_at);
  return {
    id,
    cwd,
    title: typeof row.title === "string" ? row.title : null,
    created,
    updated: jsonTimestamp(row.last_activity_at) ?? created,
    head: typeof row.head === "number" && Number.isSafeInteger(row.head) ? row.head : null,
  };
}
/** The session as it is now, still in this workspace and not one Devin hides. */
function ownedSession(source: Source, ref: string, workspace: string): Session {
  if (!SESSION_ID.test(ref)) throw new Error("Invalid Devin session reference");
  const row = source.db
    .prepare(`SELECT ${SESSION_COLUMNS(source)} FROM sessions WHERE id=? AND hidden=0`)
    .get(ref);
  const session = row ? sessionRow(row) : null;
  if (!session || !within(session.cwd, workspace))
    throw new Error("Devin session is no longer available in this workspace");
  return session;
}

interface Call {
  id: string;
  name: string;
}
interface Node {
  node: number;
  valid: boolean;
  role: string;
  /** Typed by the user, rather than added to the conversation by Devin. */
  input: boolean;
  text: boolean;
  images: number;
  message: string | null;
  /** On a compaction summary: the last node of the history it replaced. */
  summarized: number | null;
  /** On a tool result: the call it answers. */
  result: string | null;
  phase: string | null;
  thinking: boolean;
  calls: Call[];
  time: string | null;
}
// Only identities and flags: bodies are read for the nodes a page or document needs.
const CHAIN = `WITH RECURSIVE chain(node_id,parent_node_id,depth) AS (
  SELECT node_id,parent_node_id,0 FROM message_nodes WHERE session_id=?1 AND node_id=?2
  UNION ALL
  SELECT m.node_id,m.parent_node_id,c.depth+1 FROM message_nodes m JOIN chain c
    ON m.session_id=?1 AND m.node_id=c.parent_node_id WHERE c.depth<?3
)
SELECT c.node_id AS node,c.depth AS depth,json_valid(m.chat_message) AS valid,
  CASE WHEN json_valid(m.chat_message) THEN json_extract(m.chat_message,'$.role') END AS role,
  CASE WHEN json_valid(m.chat_message) THEN json_extract(m.chat_message,'$.metadata.is_user_input') END AS input,
  CASE WHEN json_valid(m.chat_message) AND json_type(m.chat_message,'$.content')='text'
    THEN length(trim(json_extract(m.chat_message,'$.content'),char(32,9,10,13)))>0 END AS text,
  CASE WHEN json_valid(m.chat_message) AND json_type(m.chat_message,'$.images')='array'
    THEN json_array_length(m.chat_message,'$.images') END AS images,
  CASE WHEN json_valid(m.chat_message) THEN json_extract(m.chat_message,'$.message_id') END AS message,
  CASE WHEN json_valid(m.chat_message) THEN json_extract(m.chat_message,'$.tool_call_id') END AS result,
  CASE WHEN json_valid(m.chat_message) THEN json_extract(m.chat_message,'$.phase') END AS phase,
  CASE WHEN json_valid(m.chat_message) AND json_type(m.chat_message,'$.thinking.thinking')='text'
    THEN length(json_extract(m.chat_message,'$.thinking.thinking'))>0 END AS thinking,
  CASE WHEN json_valid(m.chat_message) AND json_type(m.chat_message,'$.tool_calls')='array'
    THEN (SELECT json_group_array(json_array(json_extract(t.value,'$.id'),json_extract(t.value,'$.name')))
      FROM json_each(m.chat_message,'$.tool_calls') t) END AS calls,
  CASE WHEN json_valid(m.chat_message) THEN json_extract(m.chat_message,'$.metadata.created_at') END AS at,
  CASE WHEN json_valid(m.metadata) THEN json_extract(m.metadata,'$.summarized_from') END AS summarized,
  m.created_at AS created
FROM chain c JOIN message_nodes m ON m.session_id=?1 AND m.node_id=c.node_id
ORDER BY c.depth DESC`;
const integer = (value: unknown) =>
  typeof value === "number" && Number.isSafeInteger(value) ? value : null;
const nonEmpty = (value: unknown) => (typeof value === "string" && value ? value : null);
function nodeRow(row: Row): Node {
  let calls: Call[] = [];
  if (typeof row.calls === "string")
    try {
      const parsed: unknown = JSON.parse(row.calls);
      if (Array.isArray(parsed))
        calls = parsed.flatMap((entry) =>
          Array.isArray(entry) && nonEmpty(entry[0]) && Buffer.byteLength(entry[0]) <= 512
            ? [{ id: entry[0] as string, name: nonEmpty(entry[1]) ?? "tool" }]
            : [],
        );
    } catch {
      calls = [];
    }
  return {
    node: Number(row.node),
    valid: row.valid === 1,
    role: typeof row.role === "string" ? row.role : "",
    input: row.input === 1,
    text: row.text === 1,
    images: integer(row.images) ?? 0,
    message: nonEmpty(row.message),
    summarized: integer(row.summarized),
    result: nonEmpty(row.result),
    phase: nonEmpty(row.phase),
    thinking: row.thinking === 1,
    calls,
    time: jsonTimestamp(row.at) ?? jsonTimestamp(row.created),
  };
}

interface Segment {
  nodes: Node[];
  /** The compaction summary this segment starts from; the first segment has none. */
  summary: Node | null;
}
interface History {
  segments: Segment[];
  partial: boolean;
}
/**
 * A Devin session is a tree of message nodes. The active conversation is the path from
 * `main_chain_id` back to its root; after a compaction that path starts with a system summary
 * whose `summarized_from` names the last node of the history it replaced, on another branch.
 * Following those links recovers the whole conversation, oldest segment first.
 */
function readHistory(source: Source, session: Session): History {
  const segments: Segment[] = [];
  const seen = new Set<number>();
  let remaining = MAX_NODES;
  let partial = false;
  let head = session.head;
  while (head !== null) {
    if (seen.has(head) || segments.length >= MAX_SEGMENTS || remaining <= 0) {
      partial = true;
      break;
    }
    seen.add(head);
    const rows = source.db.prepare(CHAIN).all(session.id, head, remaining);
    if (!rows.length) {
      // The newest head is gone only if the session changed; an older link can be missing.
      partial = true;
      break;
    }
    if (rows.length > remaining) partial = true;
    remaining -= rows.length;
    const chain = rows.map(nodeRow);
    let index = chain.length - 1;
    while (index >= 0 && chain[index]!.summarized === null) index--;
    if (index < 0) {
      segments.unshift({ nodes: chain, summary: null });
      break;
    }
    segments.unshift({ nodes: chain.slice(index + 1), summary: chain[index]! });
    head = chain[index]!.summarized;
  }
  return { segments, partial };
}

type Item =
  | { type: "user"; id: string; turn: string; node: Node }
  | {
      type: "reply";
      id: string;
      turn?: string;
      node: Node;
      phase?: "commentary" | "final_answer";
    }
  | {
      type: "tool";
      id: string;
      turn?: string;
      node: Node;
      call: Call;
      result: Node | null;
    };
/**
 * Conversation items of a run of nodes: what the user typed, Devin's replies and its tool calls.
 * System messages, injected context and reasoning are not items. A chain Devin copied (after a
 * model switch, say) repeats earlier messages under the same message ID; `seen` keeps the first.
 */
function project(nodes: Node[], seen: Set<string>, state: { turn?: string } = {}): Item[] {
  const results = new Map<string, Node>();
  for (const node of nodes)
    if (node.role === "tool" && node.result && !results.has(node.result))
      results.set(node.result, node);
  const items: Item[] = [];
  for (const node of nodes) {
    if (!node.valid || (node.role !== "user" && node.role !== "assistant")) continue;
    if (node.message !== null && seen.has(node.message)) continue;
    const id = `devin-${node.message ?? `node-${node.node}`}`;
    if (node.role === "user") {
      if (!node.input || (!node.text && !node.images)) continue;
      if (node.message !== null) seen.add(node.message);
      state.turn = id;
      items.push({ type: "user", id, turn: id, node });
      continue;
    }
    if (node.message !== null) seen.add(node.message);
    if (node.text) items.push({ type: "reply", id, turn: state.turn, node });
    for (const call of node.calls)
      items.push({
        type: "tool",
        id: `devin-tool-${call.id}`,
        turn: state.turn,
        node,
        call,
        result: results.get(call.id) ?? null,
      });
  }
  return items;
}
/**
 * Devin marks few answers explicitly. Otherwise a turn's answer is its last reply when no tool
 * call follows it; every other reply is commentary. A turn still running has no answer yet.
 */
function phases(items: Item[]): void {
  let replies: Extract<Item, { type: "reply" }>[] = [];
  let last: Item | undefined;
  const settle = () => {
    const marked = replies.filter((reply) => reply.node.phase === "final_answer");
    const final =
      marked[marked.length - 1] ??
      (last?.type === "reply" && !last.node.calls.length ? last : undefined);
    for (const reply of replies) reply.phase = reply === final ? "final_answer" : "commentary";
    replies = [];
  };
  for (const item of items) {
    if (item.type === "user") settle();
    else if (item.type === "reply") replies.push(item);
    last = item;
  }
  settle();
}

interface Body {
  content: string | null;
  truncated: boolean;
  images: { mime: string | null; size: number }[];
  arguments: Map<string, string>;
}
const BODY = `SELECT node_id AS node,
  CASE WHEN json_type(chat_message,'$.content')='text' THEN substr(json_extract(chat_message,'$.content'),1,?3) END AS content,
  CASE WHEN json_type(chat_message,'$.content')='text' THEN length(json_extract(chat_message,'$.content')) END AS length,
  CASE WHEN json_type(chat_message,'$.images')='array'
    THEN (SELECT json_group_array(json_array(json_extract(i.value,'$.mime_type'),length(json_extract(i.value,'$.base64_data'))))
      FROM json_each(chat_message,'$.images') i) END AS images,
  CASE WHEN json_type(chat_message,'$.tool_calls')='array'
    THEN (SELECT json_group_array(json_array(json_extract(t.value,'$.id'),substr(json_extract(t.value,'$.arguments'),1,?3)))
      FROM json_each(chat_message,'$.tool_calls') t) END AS calls
FROM message_nodes WHERE session_id=?1 AND node_id IN (SELECT value FROM json_each(?2)) AND json_valid(chat_message)`;
function jsonArray(value: unknown): unknown[] {
  if (typeof value !== "string") return [];
  try {
    const parsed: unknown = JSON.parse(value);
    return Array.isArray(parsed) ? parsed : [];
  } catch {
    return [];
  }
}
function readBodies(source: Source, session: string, nodes: number[]): Map<number, Body> {
  const result = new Map<number, Body>();
  if (!nodes.length) return result;
  for (const row of source.db
    .prepare(BODY)
    .all(session, JSON.stringify([...new Set(nodes)]), MAX_TEXT_CHARS)) {
    const length = integer(row.length) ?? 0;
    result.set(Number(row.node), {
      content: typeof row.content === "string" ? row.content : null,
      truncated: length > MAX_TEXT_CHARS,
      images: jsonArray(row.images).map((entry) => ({
        mime: Array.isArray(entry) && typeof entry[0] === "string" ? entry[0].toLowerCase() : null,
        size: Array.isArray(entry) ? (integer(entry[1]) ?? 0) : 0,
      })),
      arguments: new Map(
        jsonArray(row.calls).flatMap((entry) =>
          Array.isArray(entry) && nonEmpty(entry[0]) && typeof entry[1] === "string"
            ? [[entry[0] as string, entry[1]] as const]
            : [],
        ),
      ),
    });
  }
  return result;
}

interface ToolState {
  call: unknown;
  update: unknown;
  reduced: boolean;
}
// Oversized states keep the fields a row shows; their full content is not parsed.
const TOOL_STATE = `SELECT tool_call_id AS id,
  CASE WHEN length(tool_call_json)<=?3 THEN tool_call_json
    WHEN json_valid(tool_call_json) THEN json_object('kind',json_extract(tool_call_json,'$.kind'),
      'title',substr(json_extract(tool_call_json,'$.title'),1,4096),
      'locations',json(coalesce(json_extract(tool_call_json,'$.locations'),'[]')),
      'rawInput',json_object('command',substr(json_extract(tool_call_json,'$.rawInput.command'),1,65536))) END AS call,
  CASE WHEN length(tool_call_update_json)<=?3 THEN tool_call_update_json
    WHEN json_valid(tool_call_update_json) THEN json_object('status',json_extract(tool_call_update_json,'$.status')) END AS progress,
  coalesce(length(tool_call_json)>?3,0) OR coalesce(length(tool_call_update_json)>?3,0) AS reduced
FROM tool_call_state WHERE session_id=?1 AND tool_call_id IN (SELECT value FROM json_each(?2))`;
function parsed(value: unknown): unknown {
  if (typeof value !== "string") return undefined;
  try {
    return JSON.parse(value);
  } catch {
    return undefined;
  }
}
function readToolStates(source: Source, session: string, calls: string[]): Map<string, ToolState> {
  const result = new Map<string, ToolState>();
  if (!source.tools || !calls.length) return result;
  for (const row of source.db
    .prepare(TOOL_STATE)
    .all(session, JSON.stringify([...new Set(calls)]), MAX_TOOL_JSON_CHARS))
    result.set(String(row.id), {
      call: parsed(row.call),
      update: parsed(row.progress),
      reduced: row.reduced === 1,
    });
  return result;
}
/** The ACP kind of a native tool, for the rare call whose ACP state Devin did not save. */
function nativeKind(name: string): string {
  if (["exec", "get_output", "write_to_process", "kill_shell"].includes(name)) return "execute";
  if (["read", "notebook_read"].includes(name)) return "read";
  if (["edit", "write", "apply_patch", "notebook_edit"].includes(name)) return "edit";
  if (["grep", "glob", "find_file_by_name", "code_search"].includes(name)) return "search";
  if (["webfetch", "web_search"].includes(name)) return "fetch";
  if (name === "todo_write") return "think";
  return "other";
}
function toolEvent(
  item: Extract<Item, { type: "tool" }>,
  state: ToolState | undefined,
  argumentsText: string | undefined,
  output: string | null,
  context: ToolContext,
): ConversationEvent {
  const call = state?.call ?? {
    kind: nativeKind(item.call.name),
    rawInput: parsed(argumentsText) ?? argumentsText,
  };
  const update =
    state?.update ??
    (item.result
      ? {
          status: "completed",
          content: output ? [{ type: "content", content: { type: "text", text: output } }] : [],
        }
      : {});
  const normalized = acpToolCall(call, update, item.call.name, context);
  if (state?.reduced) normalized.detail.truncated = true;
  const event: ConversationEvent = {
    id: item.id,
    kind: "tool-summary",
    timestamp: item.node.time,
    content: null,
    tool_name: normalized.name,
    tool_status: normalized.status ?? (item.result ? "completed" : null),
    duration_ms: null,
    attachment_count: 0,
    truncated: false,
    tool: normalized.detail,
  };
  if (item.turn) event.turn_id = item.turn;
  return event;
}
function imagesOf(node: Node, body: Body | undefined): ConversationImage[] {
  return (body?.images ?? []).flatMap((image, index) =>
    image.mime && IMAGE_TYPES.has(image.mime) && image.size > 0 && image.size <= MAX_IMAGE_CHARS
      ? [{ id: `devin-image-${node.node}-${index}`, mimeType: image.mime }]
      : [],
  );
}
function messageEvent(
  item: Exclude<Item, { type: "tool" }>,
  body: Body | undefined,
): ConversationEvent {
  const text = body?.content && /[^\p{White_Space}]/u.test(body.content) ? body.content : null;
  const bounded = text === null ? { content: null, truncated: false } : truncateUtf8(text);
  const images = item.type === "user" ? imagesOf(item.node, body) : [];
  const event: ConversationEvent = {
    id: item.id,
    kind: item.type === "user" ? "user-message" : "agent-message",
    timestamp: item.node.time,
    content: bounded.content,
    tool_name: null,
    tool_status: null,
    duration_ms: null,
    attachment_count: item.type === "user" ? item.node.images : 0,
    truncated: bounded.truncated || body?.truncated === true,
  };
  if (images.length) event.images = images;
  if (item.turn) event.turn_id = item.turn;
  if (item.type === "reply" && item.phase) event.message_phase = item.phase;
  return event;
}
function eventBytes(event: ConversationEvent): number {
  return Buffer.byteLength(event.content ?? "") + toolEventBytes(event) + 256;
}

