import type { DshBridgeDocumentRecord, HistoryRecordKind } from "@agentkib/runtime-protocol";
import { finishDocument, type DocumentSource } from "./session-document-providers";
import type { DocumentOptions, SessionDocument } from "./session-model";

type Turn = SessionDocument["turns"][number];
type LossCode = SessionDocument["losses"][number]["code"];
/** An image a user message carried, read from DSH; absent when it could not be read. */
export type DshDocumentImage = { mediaType: string; base64: string };

// Fixed English annotations, as for Claude Code: every target format only has user and assistant
// roles, so the text itself must say the user did not write it.
const SUMMARY_NOTICE =
  "[AgentKib: context summary generated by DeepSeek Harness when it compacted this conversation. It summarizes earlier turns and is not a message written by the user.]";

const iso = (time: number | null) => (time === null ? null : new Date(time).toISOString());

/**
 * A DSH session as a handoff document. By default it holds what DSH's model sees now: the summary
 * of each compaction and what followed it, with the replaced history counted as
 * `compacted-history`. `includePreCompactionHistory` keeps every record in order instead, with a
 * marker where DSH compacted. DSH's log is append-only, so nothing a compaction replaced is lost.
 */
export function dshSessionDocument(
  source: DocumentSource,
  records: DshBridgeDocumentRecord[],
  images: Map<string, DshDocumentImage | null>,
  options: DocumentOptions = {},
): SessionDocument {
  const withHistory = options.includePreCompactionHistory === true;
  const losses = new Map<LossCode, number>();
  const loss = (code: LossCode, count = 1) => {
    if (count > 0) losses.set(code, (losses.get(code) ?? 0) + count);
  };
  const turns: Turn[] = [];
  const calls = new Set<string>();
  // DSH can replace a tool result with a shorter one; the full history keeps the original.
  const results = new Set<string>();
  const total = records.filter((record) => record.kind === "summary").length;
  let compactions = 0;
  let replaced = 0;
  // What the model sees now is in surface order: a compaction's summary stands where the history
  // it replaced was, ahead of a later message it left. The full history keeps log order.
  const ordered = withHistory
    ? records
    : records
        .filter((record) => record.current)
        .sort((a, b) => (a.position ?? 0) - (b.position ?? 0));
  if (!withHistory)
    for (const record of records)
      if (!record.current && (record.kind !== "assistant" || record.text || record.calls.length))
        replaced++;
  for (const record of ordered) {
    if (record.kind === "tool-result" && record.callId) {
      if (results.has(record.callId)) continue;
      results.add(record.callId);
    }
    if (record.truncated) loss("source-content-truncated");
    const id = `dsh-${record.seq}`;
    const timestamp = iso(record.time);
    switch (record.kind) {
      case "user": {
        const blocks: Turn["blocks"] = record.text.trim()
          ? [{ type: "text", text: record.text }]
          : [];
        for (const image of record.images) {
          const read = images.get(image.attachmentId);
          if (read)
            blocks.push({
              type: "attachment",
              kind: "image",
              media_type: read.mediaType,
              ...(image.name ? { filename: image.name } : {}),
              inline_base64: read.base64,
            });
          else loss("external-attachment");
        }
        loss("external-attachment", record.files);
        if (blocks.length) turns.push({ id, role: "user", timestamp, blocks });
        break;
      }
      case "assistant": {
        if (record.reasoning) loss("reasoning-excluded");
        const blocks: Turn["blocks"] = record.text.trim()
          ? [{ type: "text", text: record.text }]
          : [];
        for (const [index, call] of record.calls.entries()) {
          const callId = call.id || `${id}-call-${index}`;
          calls.add(callId);
          if (call.truncated) loss("source-content-truncated");
          blocks.push({
            type: "tool-call",
            call_id: callId,
            name: call.name || "tool",
            input: call.arguments,
          });
        }
        if (blocks.length) turns.push({ id, role: "assistant", timestamp, blocks });
        break;
      }
      case "tool-result":
        if (!calls.has(record.callId)) loss("orphan-tool-result");
        loss("external-attachment", record.images);
        turns.push({
          id,
          role: "tool",
          timestamp,
          blocks: [
            {
              type: "tool-result",
              call_id: record.callId || `${id}-result`,
              output: record.text,
              is_error: record.isError,
            },
          ],
        });
        break;
      case "summary":
        compactions++;
        if (withHistory)
          turns.push({
            id: `dsh-boundary-${record.seq}`,
            role: "user",
            kind: "compaction-boundary",
            timestamp,
            blocks: [
              {
                type: "text",
                text: `[AgentKib: DeepSeek Harness compacted the conversation here (compaction ${compactions} of ${total}). Messages above are the original earlier history; the context summary below is what DeepSeek Harness carried forward.]`,
              },
            ],
          });
        turns.push({
          id: `dsh-summary-${record.seq}`,
          role: "user",
          kind: "context-summary",
          timestamp,
          blocks: [{ type: "text", text: `${SUMMARY_NOTICE}\n\n${record.text}` }],
        });
        break;
    }
  }
  loss("compacted-history", replaced);
  return finishDocument(source, turns, losses);
}

/** A record for content search; the common sink sanitizes it before it is stored. */
export interface DshSearchRecord {
  recordId: string;
  kind: HistoryRecordKind;
  toolName: string | null;
  timestamp: string | null;
  content: string;
  truncated: boolean;
}

/**
 * What content search finds in a DSH session: every message, tool input and tool output in the
 * log, as AgentKib's conversation view shows them, including history a compaction replaced.
 * Compaction summaries are DSH's, not the conversation's, and are left out.
 */
export function dshSearchRecords(records: DshBridgeDocumentRecord[]): DshSearchRecord[] {
  const names = new Map<string, string>();
  const out: DshSearchRecord[] = [];
  const add = (record: Omit<DshSearchRecord, "truncated">, truncated: boolean) => {
    if (record.content.trim()) out.push({ ...record, truncated });
  };
  for (const record of records) {
    const timestamp = iso(record.time);
    switch (record.kind) {
      case "user":
      case "assistant":
        add(
          {
            recordId: `dsh:${record.seq}:text`,
            kind: record.kind,
            toolName: null,
            timestamp,
            content: record.text,
          },
          record.truncated,
        );
        if (record.kind === "assistant")
          for (const [index, call] of record.calls.entries()) {
            const callId = call.id || `dsh:${record.seq}:${index}`;
            names.set(callId, call.name);
            add(
              {
                recordId: `call:${callId}:input`,
                kind: "tool-input",
                toolName: call.name || null,
                timestamp,
                content: call.arguments,
              },
              call.truncated,
            );
          }
        break;
      case "tool-result":
        add(
          {
            recordId: `call:${record.callId || `dsh:${record.seq}`}:output`,
            kind: "tool-output",
            toolName: names.get(record.callId) || null,
            timestamp,
            content: record.text,
          },
          record.truncated,
        );
        break;
    }
  }
  return out;
}
