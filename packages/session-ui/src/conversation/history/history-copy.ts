export function historySearchCopy(
  locale: Locale,
  entry: SessionPlatform["historySearch"]["entry"],
) {
  const copy = historyCopy[locale];
  return entry === "workspace" ? { ...copy, ...workspaceCopy[locale] } : copy;
}
